-- 1. TABELA JOGOS
CREATE TABLE IF NOT EXISTS public.jogos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABELA PERGUNTAS
CREATE TABLE IF NOT EXISTS public.perguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enunciado TEXT NOT NULL,
    alternativa_a TEXT NOT NULL,
    alternativa_b TEXT NOT NULL,
    alternativa_c TEXT NOT NULL,
    alternativa_d TEXT NOT NULL,
    correta CHAR(1) NOT NULL CHECK (correta IN ('A', 'B', 'C', 'D')),
    dificuldade TEXT NOT NULL CHECK (dificuldade IN ('facil', 'media', 'dificil')),
    fonte TEXT
);

-- 3. TABELA PARTIDAS
CREATE TABLE IF NOT EXISTS public.partidas (
    id UUID PRIMARY KEY,
    jogo_id BIGINT NOT NULL REFERENCES public.jogos(id) ON DELETE CASCADE,
    apelido TEXT NOT NULL,
    valor_ganho NUMERIC NOT NULL DEFAULT 0,
    tempo_segundos NUMERIC NOT NULL DEFAULT 0,
    acertos INTEGER NOT NULL DEFAULT 0,
    motivo_encerramento TEXT NOT NULL,
    data_hora TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices para performance
CREATE INDEX IF NOT EXISTS idx_partidas_jogo_ranking ON public.partidas (jogo_id, valor_ganho DESC, tempo_segundos ASC);
CREATE INDEX IF NOT EXISTS idx_perguntas_dificuldade ON public.perguntas (dificuldade);

-- 4. VIEW DO RANKING
-- Regra de negócio:
-- - Separado por jogo (jogo_id)
-- - Seleciona apenas a melhor partida de cada apelido (sem duplicação de apelido)
-- - Critérios de desempate:
--   1º Maior valor ganho
--   2º Menor tempo em segundos
--   3º Data mais antiga
--   4º ID da partida
-- - Exibe posição (1º ao 10º)
CREATE OR REPLACE VIEW public.ranking AS
WITH melhor_partida_por_jogador AS (
    SELECT 
        p.id AS partida_id,
        p.jogo_id,
        j.nome AS nome_jogo,
        p.apelido,
        p.valor_ganho,
        p.tempo_segundos,
        p.data_hora,
        ROW_NUMBER() OVER (
            PARTITION BY p.jogo_id, LOWER(TRIM(p.apelido))
            ORDER BY 
                p.valor_ganho DESC,
                p.tempo_segundos ASC,
                p.data_hora ASC,
                p.id ASC
        ) AS rn
    FROM public.partidas p
    JOIN public.jogos j ON j.id = p.jogo_id
),
partidas_filtradas AS (
    SELECT *
    FROM melhor_partida_por_jogador
    WHERE rn = 1
)
SELECT 
    partida_id,
    jogo_id,
    nome_jogo,
    apelido,
    valor_ganho,
    tempo_segundos,
    data_hora,
    ROW_NUMBER() OVER (
        PARTITION BY jogo_id
        ORDER BY 
            valor_ganho DESC,
            tempo_segundos ASC,
            data_hora ASC,
            partida_id ASC
    ) AS posicao
FROM partidas_filtradas;

